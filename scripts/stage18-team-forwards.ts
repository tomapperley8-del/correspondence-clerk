/**
 * Stage 18: emails Tom's team forwarded in, filed under the team member instead of the
 * business that first wrote. Read-only: works out where each belongs (lib/inbound/team-forwards.ts,
 * the inbound route's reading) and writes a proposal plus the SQL to apply it. Changes nothing.
 *
 *   npx tsx scripts/stage18-team-forwards.ts <out-dir>
 *
 * Reads NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY (the local copy's, normally).
 * A move happens only when the original sender is a contact at exactly one business that is
 * not the team's; everything else is left for Tom on /review/team-forwards. Entry ids listed in
 * <out-dir>/hold_17a_groupB.txt (Stage 17a's "needs Tom" list on Cleo's record) are never moved.
 * Text is never changed (Hard Rule 10): only business_id, contact_id, and reply_dismissed_at on
 * received ones (the team member already dealt with it, so it stays off "Waiting on you").
 */
import { createClient } from '@supabase/supabase-js'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs'
import { join } from 'path'
import { findTeamForwards } from '../lib/inbound/team-forwards'

const OUT = process.argv[2] ?? 'supabase/.local/18'
const REASON = 'stage18 team forwards 2026-10-30'
const holdFile = join(OUT, 'hold_17a_groupB.txt')
const idsIn = (file: string) => (existsSync(file) ? readFileSync(file, 'utf8').match(/^[0-9a-f][0-9a-f-]{7,35}/gm) ?? [] : [])
// Ids or 8-character prefixes. Held: never moved, listed for Tom. Kept: Tom said they stay on the
// team member's record (marked team_forward_kept, so the review page leaves them out too).
const HOLD_PREFIXES = idsIn(holdFile)
const KEEP_PREFIXES = idsIn(join(OUT, 'keep_on_team.txt'))
const hasPrefix = (list: string[], id: string) => list.some((p) => id.startsWith(p))

const supabase = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.SUPABASE_SERVICE_ROLE_KEY!, { auth: { persistSession: false } })

async function main() {
  const { data: org } = await supabase.from('organizations').select('id').order('created_at').limit(1).single()
  const found = await findTeamForwards(supabase, org!.id)
  const held = new Set([...found.moves, ...found.review].map((x) => x.id).filter((id) => hasPrefix(HOLD_PREFIXES, id)))
  const r = held.size ? await findTeamForwards(supabase, org!.id, held) : found
  const kept = [...r.moves, ...r.review].filter((x) => hasPrefix(KEEP_PREFIXES, x.id))
  r.moves = r.moves.filter((m) => !hasPrefix(KEEP_PREFIXES, m.id))
  r.review = r.review.filter((m) => !hasPrefix(KEEP_PREFIXES, m.id))
  const summary = {
    team: r.team, team_records: r.teamRecords, moves: r.moves.length, review: r.review.length, stay: r.stay, kept: kept.length,
    by_team_member: Object.fromEntries(r.teamRecords.map((n) => [n, {
      move: r.moves.filter((m) => m.team_name === n).length, review: r.review.filter((x) => x.team_name === n).length,
    }])),
  }
  mkdirSync(OUT, { recursive: true })
  writeFileSync(join(OUT, 'team_forwards.json'), JSON.stringify({ summary, moves: r.moves, review: r.review }, null, 2))

  const backupIds = [...r.moves, ...kept].map((m) => `'${m.id}'`).join(',\n  ')
  writeFileSync(join(OUT, 'team_forwards_apply.sql'), [
    `-- Stage 18: move ${r.moves.length} team forwards to the business that first wrote (generated by scripts/stage18-team-forwards.ts).`,
    `-- Text untouched. Before-images in cc_phase0_backup, reason '${REASON}'. Undo: supabase/data-fixes/20261030_stage18_team_forwards_undo.sql`,
    `-- Each UPDATE checks the entry is still on the team member's record, so a re-run or an entry moved by hand is left alone.`,
    'BEGIN;',
    `INSERT INTO cc_phase0_backup (table_name, row_id, before_row, reason)`,
    `SELECT 'correspondence', c.id, to_jsonb(c), '${REASON}' FROM correspondence c WHERE c.id IN (\n  ${backupIds || 'NULL'}\n);`,
    ...r.moves.map((m) => `UPDATE correspondence SET business_id = '${m.to_business_id}', contact_id = '${m.contact_id}'` +
      `${m.direction === 'received' && !m.reply_dismissed_at ? ', reply_dismissed_at = now()' : ''}, updated_at = now()` +
      ` WHERE id = '${m.id}' AND business_id = '${m.team_business_id}';  -- ${m.team_name} -> ${m.to_name.replace(/\s+/g, ' ')}`),
    ...kept.map((k) => `UPDATE correspondence SET ai_metadata = coalesce(ai_metadata, '{}'::jsonb) || '{"team_forward_kept": true}'::jsonb` +
      ` WHERE id = '${k.id}' AND business_id = '${k.team_business_id}';  -- kept on ${k.team_name} (Tom)`),
    'COMMIT;', '',
  ].join('\n'))
  console.log(JSON.stringify(summary, null, 2))
}

main().catch((e) => { console.error(e); process.exit(1) })
